package Basics;

public class AssignValue {
    public static void main(String[] args) {
        int x = 5;
        System.out.println(x);
        int y = 10;
        System.out.println(y);
        x = y + 3;
        System.out.println(x);
        x=y;//here we are assinging the value of y to x.
        System.out.println(x);
    }
}
